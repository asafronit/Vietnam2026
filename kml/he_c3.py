for fname, table in (('buon-ma-thuot', BMT), ('lak-lake', LAK), ('da-lat', DA_LAT)):
    p = 'data/%s.yaml' % fname
    d = yaml.safe_load(io.open(p, encoding='utf-8'))
    miss = []
    n = 0
    for k, v in d.items():
        if not isinstance(v, list):
            continue
        for r in v:
            nm = r.get('name')
            if nm in table:
                r['name_he'], r['area_he'], r['what_he'], r['why_he'] = table[nm]
                n += 1
            else:
                miss.append(nm)
    d['hebrew_complete'] = True
    io.open(p, 'w', encoding='utf-8', newline='\n').write(
        yaml.dump(d, allow_unicode=True, sort_keys=False, default_flow_style=False, width=88))
    print(fname, 'translated', n, ('MISSING: %s' % miss) if miss else '')
